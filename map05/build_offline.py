"""Build a double-clickable, network-free copy of MAP-05 from its local sources."""
import base64
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent


def digest(text):
    return base64.b64encode(hashlib.sha256(text.encode('utf-8')).digest()).decode('ascii')


def build():
    fixture_text = (ROOT.parent / 'map04' / 'fixtures.json').read_text(encoding='utf-8')
    fixture = json.loads(fixture_text)
    if fixture.get('synthetic_only') is not True:
        raise ValueError('Only a synthetic MAP-04 fixture may be bundled.')
    css = (ROOT / 'styles.css').read_text(encoding='utf-8')
    model = (ROOT / 'model.mjs').read_text(encoding='utf-8').replace('export function ', 'function ')
    map_code = (ROOT / 'map.mjs').read_text(encoding='utf-8').replace('export function ', 'function ')
    basemap = json.loads((ROOT / 'basemap' / 'data.json').read_text(encoding='utf-8'))
    if not all(basemap.get('regions', {}).get(region, {}).get('features') for region in ['OPO', 'KNU']):
        raise ValueError('Both real basemap extracts must be present.')
    app = (ROOT / 'app.mjs').read_text(encoding='utf-8')
    app = re.sub(r'^import[^\n]*\n', '', app, flags=re.MULTILINE)
    script = '(function(){\n"use strict";\n' + model + '\n' + map_code + '\n' + app + '\n})();'
    # Escape script delimiters even if a future synthetic label contains markup.
    script = script.replace('</script', '<\\/script')
    data = json.dumps(fixture, ensure_ascii=False).replace('<', '\\u003c')
    map_data = json.dumps(basemap, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c')
    csp = f"default-src 'none'; connect-src 'none'; script-src 'sha256-{digest(script)}' 'sha256-{digest(data)}' 'sha256-{digest(map_data)}'; style-src 'sha256-{digest(css)}'; img-src data:; object-src 'none'; base-uri 'none'; form-action 'none'"
    html = (ROOT / 'index.html').read_text(encoding='utf-8')
    html = re.sub(r'<meta http-equiv="Content-Security-Policy"[^>]+>', f'<meta http-equiv="Content-Security-Policy" content="{csp}">', html)
    favicon = base64.b64encode((ROOT / 'favicon.svg').read_bytes()).decode('ascii')
    html = html.replace('href="./favicon.svg"', f'href="data:image/svg+xml;base64,{favicon}"')
    html = html.replace('<link rel="stylesheet" href="./styles.css">', '<style>' + css + '</style>')
    html = html.replace('  <script type="module" src="./app.mjs"></script>\n', '')
    html = html.replace('href="./"', 'href="./offline.html"')
    html = html.replace('href="./planner.html"', 'href="./planner-offline.html"')
    html = html.replace('</body>', '<script id="map04-data" type="application/json">' + data + '</script>\n<script id="basemap-data" type="application/json">' + map_data + '</script>\n<script>' + script + '</script>\n</body>')
    fixture_sha = hashlib.sha256(fixture_text.encode('utf-8')).hexdigest()
    html = html.replace('<!doctype html>', f'<!doctype html>\n<!-- Generated by build_offline.py; MAP-04 source SHA256: {fixture_sha} -->')
    (ROOT / 'offline.html').write_text(html, encoding='utf-8', newline='\n')
    print(f'Built map05/offline.html ({len(html.encode("utf-8"))} bytes), fixture SHA256: {fixture_sha}')
    return html


if __name__ == '__main__':
    build()
